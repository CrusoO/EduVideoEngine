import { describe, expect, it } from "vitest";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { FIXTURES_DIR, FixtureStore, Ledger, LlmClient, testConfig } from "@eve/adapters";
import { buildLesson } from "../build";
import { ARC_PLANNER_VERSION } from "../arcplan";
import { SCRIPTWRITER_VERSION } from "../script";
import { SKILL, STORE, context } from "./fixtures";

/**
 * The model's own answers, recorded on 2026-10-20 (`minimax/minimax-m3.1-flash:free`, ADR 0060): the arc planner (repaired once) and the scriptwriter (repaired once),
 * replayed from fixtures/llm with no key and no request. This is the proof that a lesson generated by a model passes every gate (WP5): the plan and the script are
 * the model's, the claims, scenes, cues, ids and timing are code's, and the gates, the validators and the SymPy verifier judge the result as they judge the reference.
 * Replay refuses to run if a prompt or an input changed: record again, and the new recording is reviewed like any other change.
 */
const MODEL = "minimax/minimax-m3.1-flash:free";
const approvals = ["quad.sum.claim.root", "quad.sum.claim.mistake"].map((recordId) => ({ recordId, recordHash: context().hashes[recordId]! }));
const replayClient = () =>
  new LlmClient({
    config: testConfig({ provider: "openrouter", model: MODEL, mode: "replay" }),
    fixtures: new FixtureStore(FIXTURES_DIR),
    ledger: new Ledger(join(mkdtempSync(join(tmpdir(), "eve-rec-")), "l.jsonl")),
  });

describe("the lesson the model generated, replayed from its recordings", () => {
  it("is built with no request, passes every gate and the verifier, and is publishable once its two grounded claims are approved", async () => {
    const client = replayClient();
    const out = await buildLesson({ client, store: STORE, skillId: SKILL, voice: "synthetic", approvals });
    if (!out.ok) throw new Error(`${out.stage}: ${out.details.join("; ")}`);
    expect(client.stats).toMatchObject({ sent: 0, replayed: 4, repairs: 2 });
    expect(out.assurance.findings.filter((f) => f.level === "fail")).toEqual([]);
    expect(out.assurance).toMatchObject({ passes: true, verified: true, publishable: true });
    expect(out.usage.promptVersions).toMatchObject({ planner: ARC_PLANNER_VERSION, scriptwriter: SCRIPTWRITER_VERSION });
  }, 120_000);

  it("is the problem_first arc with the idea taught before it is applied, and every sentence a model wrote bound to a claim", async () => {
    const out = await buildLesson({ client: replayClient(), store: STORE, skillId: SKILL, voice: "synthetic", approvals, verify: false });
    if (!out.ok) throw new Error("build failed");
    const { bundle } = out;
    expect(bundle.plan.arcId).toBe("problem_first");
    expect(bundle.plan.beats.map((b) => b.beatKind)).toEqual(["hook", "prerequisite", "concept", "worked", "mistake", "check"]);
    // the core rule is stated in the concept beat, before the worked beat applies it
    const rule = bundle.claims!.find((c) => c.id === "quad.sum.claim.vieta")!;
    expect(rule.beatId).toBe("b3");
    // a model wrote claim and link sentences only: the rest (goals, the question, transitions) is code's, from the closed list
    for (const s of bundle.script) {
      if (s.role === "claim") expect(bundle.claims!.some((c) => c.id === s.claimId && c.beatId === s.beatId)).toBe(true);
      else expect(["goal", "transition", "question", "link"]).toContain(s.role);
    }
    expect(out.assembled.fallbacks).toEqual([]);
  }, 120_000);

  it("replay never asks a model: with a prompt it has no recording for, it refuses instead of calling out", async () => {
    const client = new LlmClient({
      config: testConfig({ provider: "openrouter", model: MODEL, mode: "replay" }),
      fixtures: new FixtureStore(mkdtempSync(join(tmpdir(), "eve-empty-"))),
      ledger: new Ledger(join(mkdtempSync(join(tmpdir(), "eve-rec-")), "l.jsonl")),
    });
    await expect(buildLesson({ client, store: STORE, skillId: SKILL, voice: "synthetic" })).rejects.toThrow(/no recorded answer for planner/);
  });
});
