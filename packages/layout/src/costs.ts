import { add, div, eq, mul, neg, num, pow, sub, sym, type Expr } from "@eve/schema";
import { measure, type LayoutObject, type MeasureCtx } from "./measure";
import { sceneCost } from "./budget";
import { solve } from "./solve";
import { DEFAULT_CHROME_PX, DESIGN_SCREEN, GAP, PAD, stageFrame } from "./tokens";

const x = sym("x");
const a = sym("a");
const b = sym("b");
/** Formulas used only to price things: a plain equation, a fraction, a nested fraction and three steps. */
const SAMPLE: Record<string, Expr> = {
  plain: eq(add(sub(pow(x, num(2)), mul(num(5), x)), num(6)), num(0)),
  fraction: eq(sym("S"), neg(div(b, a))),
  nested: eq(div(div(a, b), x), num(0)),
  f: add(sub(pow(x, num(2)), mul(num(5), x)), num(6)),
  s1: eq(mul(sub(x, num(2)), sub(x, num(3))), num(0)),
  s2: eq(add(num(2), num(3)), num(5)),
  s3: eq(neg(div(num(-5), num(1))), num(5)),
  zero: num(0),
  two: num(2),
  five: num(5),
  total: eq(add(num(2), num(3)), num(5)),
};

/** Largest number of one kind of object that fits one scene (the schema allows at most 5 objects). */
const MOST = 5;

/**
 * The price list for the composer prompt: the pixel height of every component at one stage width, and how many of each fit one scene on the
 * design phone. Generated from the same size model the solver and the build use, so the number the composer is told is the number the build checks.
 * `chromePx` is the sheet chrome parameter (ADR 0017): the default is an unconfirmed estimate.
 */
export function componentCosts(screenWidth: number = DESIGN_SCREEN.width, chromePx: number = DEFAULT_CHROME_PX) {
  const frame = stageFrame(screenWidth, DESIGN_SCREEN.height, chromePx);
  const ctx: MeasureCtx = { expressions: SAMPLE, locale: "en-IN" };
  const content = screenWidth - 2 * PAD;
  const h = (o: Omit<LayoutObject, "id">) => measure({ id: "o", ...o }, content, ctx).height;
  const text = (role: string) => ({ component: "text", props: { text: "Word", role } });

  const kinds: Record<string, Omit<LayoutObject, "id">> = {
    "text (title, one line)": text("title"),
    "text (label, one line)": text("label"),
    "text (body, one line)": text("body"),
    equation: { component: "equation", props: {}, exprRef: "plain" },
    "equation with a fraction": { component: "equation", props: {}, exprRef: "fraction" },
    "equation, large": { component: "equation", props: { size: "l" }, exprRef: "plain" },
    "stepList, 3 steps": { component: "stepList", props: { steps: ["s1", "s2", "s3"] } },
    functionGraph: { component: "functionGraph", props: {}, exprRef: "f" },
    numberLine: { component: "numberLine", props: { min: 0, max: 6 } },
    "arrowCallout, one line": { component: "arrowCallout", props: { text: "Look here", direction: "up" } },
    "shape, size m": { component: "shape", props: { kind: "rect", size: "m", color: "blue" } },
    "shape, line": { component: "shape", props: { kind: "line", size: "m", color: "blue" } },
    "highlight (overlay)": { component: "highlight", props: { target: "o" } },
  };

  const viewport = { width: frame.width, height: frame.height };
  const fit = Object.fromEntries(
    Object.entries(kinds).map(([name, o]) => {
      let n = 0;
      for (let k = 1; k <= MOST; k++) {
        const objects: LayoutObject[] = Array.from({ length: k }, (_, i) => ({ id: `o${i}`, ...o }));
        if (o.component === "highlight") break;
        if (solve({ objects, layout: [] }, viewport, ctx).contentHeight <= viewport.height) n = k;
        else break;
      }
      return [name, o.component === "highlight" ? "any number (an overlay costs no height)" : n];
    }),
  );

  return {
    note: "Generated by `pnpm gen:costs` from the layout size model. Do not edit by hand. A scene fits when padding + the heights of its objects + the gaps between them is at most the stage height.",
    generatedFor: { screen: `${DESIGN_SCREEN.width}x${DESIGN_SCREEN.height}`, stageWidth: frame.width, contentWidth: content, chromePx, chromePxIsConfirmed: false, stageHeight: frame.height },
    padding: 2 * PAD,
    gapPx: GAP,
    defaultGap: "normal",
    objectsPerScene: 5,
    costsPx: Object.fromEntries(Object.entries(kinds).map(([name, o]) => [name, h(o)])),
    textLines: {
      title: { heightPerLine: h(text("title")), charactersPerLine: Math.floor(content / (25.6 * 0.54)) },
      label: { heightPerLine: h(text("label")), charactersPerLine: Math.floor(content / (16.8 * 0.54)) },
      body: { heightPerLine: h(text("body")), charactersPerLine: Math.floor(content / (17.6 * 0.54)) },
      hindiLineHeightFactor: "1.5 for titles and 1.7 for other text: Hindi lines are 13 to 20 percent taller; allow for it",
    },
    stepListPerStepPx: { plain: 28, fraction: 40, between: GAP.tight },
    maxOfOneKindInOneScene: fit,
    exampleScenes: [
      { name: "title + equation + graph", px: sceneCost({ objects: [{ id: "a", ...text("title") }, { id: "b", ...kinds.equation! }, { id: "c", ...kinds.functionGraph! }], layout: [] }, viewport, ctx).cost },
      { name: "title + equation + number line + callout", px: sceneCost({ objects: [{ id: "a", ...text("title") }, { id: "b", ...kinds.equation! }, { id: "c", ...kinds.numberLine! }, { id: "d", ...kinds["arrowCallout, one line"]! }], layout: [] }, viewport, ctx).cost },
    ],
    rule: "If a scene is over budget, split the beat. If it cannot be split cleanly, use the template scene.",
  };
}
